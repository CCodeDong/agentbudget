# ---------------------------------------------------------------------------
# officegen's helpers render plain strings only, so "**强调**" would appear
# literally on the slide. Both slide_bullets and slide_table funnel their text
# through the module-level `_add`, so patching that one function fixes both
# without touching the shared library.
_original_add = officegen._add


def _add_with_bold(p, text, size, bold=False, color=(0x1A, 0x1A, 0x1A)):
    """Split on '**' and render the enclosed segments bold."""
    if "**" not in text:
        return _original_add(p, text, size, bold, color)

    last = None
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        r = p.add_run()
        r.text = seg
        officegen._set_font(r, size, bold or (i % 2 == 1), color)
        last = r
    return last


officegen._add = _add_with_bold


