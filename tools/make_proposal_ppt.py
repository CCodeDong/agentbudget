# slide_bullets 与 slide_table 都经由模块级 _add 输出，补丁这一个函数即可。
_original_add = officegen._add


def _add_with_bold(p, text, size, bold=False, color=(0x1A, 0x1A, 0x1A)):
    if "**" not in text:
        return _original_add(p, text, size, bold, color)
    last = None
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        r = p.add_run()
        r.text = seg
        officegen._set_font(r, size, bold or (i % 2 == 1), color)
        last = r
    return last


