def _cn(run, size=None, bold=False):
    """统一设置中西文字体，避免中文落到默认字体。"""
    run.font.name = "宋体"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    if size:
        run.font.size = Pt(size)
    run.font.bold = bold


def fill_cover(doc, project_name):
    """在封面填项目名称 / 组长 / 成员。

    模板里是三段独立文本（"项目名称"、"项 目 组 长："、"项 目 成 员："），
    所以直接在原段落后面追加 run，保持原有 18pt 字号。
    """
    for para in doc.paragraphs:
        t = para.text.strip()
        if t == "项目名称" and not para.runs[-1].text.strip().endswith("："):
            r = para.add_run(f"　{project_name}")
            _cn(r, 18, False)
        elif t == "项 目 组 长：":
            r = para.add_run(f"　{TEAM_LEADER}")
            _cn(r, 18, False)
        elif t == "项 目 成 员：":
            r = para.add_run(f"　{TEAM_MEMBERS}")
            _cn(r, 18, False)


def insert_section(doc, heading_text, blocks):
    """把 blocks 插到 heading_text 对应标题之后、下一个 Heading 之前。

    blocks: [(kind, text)]，kind 为 'p'（正文段）或 'n'（编号条目）
    """
    paras = doc.paragraphs
    start = None
    for i, p in enumerate(paras):
        if p.style.name.startswith("Heading") and heading_text in p.text:
            start = i
            break
    if start is None:
        raise RuntimeError(f"找不到标题：{heading_text}")

    # 找下一个 Heading
    end = len(paras)
    for j in range(start + 1, len(paras)):
        if paras[j].style.name.startswith("Heading"):
            end = j
            break

    anchor = paras[end] if end < len(paras) else None

    for kind, text in blocks:
        if anchor is not None:
            p = anchor.insert_paragraph_before()
        else:
            p = doc.add_paragraph()
        p.style = doc.styles["Normal"]
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.line_spacing = 1.5
        if kind == "n":
            p.paragraph_format.left_indent = Pt(18)
        r = p.add_run(text)
        _cn(r, 12)


