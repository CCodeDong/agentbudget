def build(tpl: Path, out: Path, project_name: str, sections: dict):
    # 必须用 copyfile 而不是 copy2：copy2 会连文件的「只读」属性一起复制过来
    # （模板是从附件目录取的，本身是只读的），之后 doc.save() 会 PermissionError。
    if out.exists():
        out.chmod(0o666)
        out.unlink()
    shutil.copyfile(tpl, out)
    out.chmod(0o666)

    doc = Document(out)
    fill_cover(doc, project_name)
    for heading, blocks in sections.items():
        insert_section(doc, heading, blocks)
    doc.save(out)
    return out


def main():
    OUTDIR.mkdir(parents=True, exist_ok=True)
    a = build(TPL_MOBILE, OUTDIR / "《移动应用开发》项目开题报告.docx",
              PROJECT_MOBILE, MOBILE_SECTIONS)
    b = build(TPL_CANGJIE, OUTDIR / "《仓颉语言程序设计》项目开题报告.docx",
              PROJECT_CANGJIE, CANGJIE_SECTIONS)
    for p in (a, b):
        print(f"[report] {p.name}  ({p.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
